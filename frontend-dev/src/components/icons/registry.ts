/* ---------------- 渲染 ---------------- */

function esc(s: unknown): string {
  return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')
}

export function renderShapes(shapes: IconShape[], sw: number): string {
  let out = ''
  for (let i = 0; i < shapes.length; i++) {
    const sh = shapes[i]
    if (sh.t === '支') {
      out +=
        '<text x="' + sh.x + '" y="' + sh.y + '" text-anchor="middle" dominant-baseline="central" ' +
        "font-family=\"'Noto Sans SC','PingFang SC',sans-serif\" font-size=\"" + (sh.fs || 14) + '" font-weight="700" fill="' + sh.f + '">' + sh.t + '</text>'
      continue
    }
    const isFill = sh.f === true
    let fill: string
    if (sh.f === undefined || sh.f === 'none') fill = 'fill="none"'
    else if (isFill) fill = 'fill="currentColor"'
    else fill = 'fill="' + sh.f + '"'
    let stroke = ''
    if (!isFill && (sh.f === undefined || sh.s !== undefined)) {
      const col = sh.s === undefined ? 'currentColor' : sh.s
      stroke = ' stroke="' + col + '"'
    }
    const fw = String(sh.sw || sw || 1.8)
    out += '<path d="' + esc(sh.p) + '"' + stroke + ' stroke-width="' + fw + '" stroke-linecap="round" stroke-linejoin="round" ' + fill + (isFill ? ' stroke="none"' : '') + '/>'
  }
  return out
}

export function iconExists(name: string): boolean {
  return name in UI_ICONS || name in BRAND_ICONS
}

/* 生成完整 <svg> 字符串；未知名称返回空串 */
export function buildIcon(name: string, size: number, sw: number): string {
  const def = UI_ICONS[name]
  let inner = ''
  if (def) inner = renderShapes(def, sw || 1.8)
  else {
    const b = BRAND_ICONS[name]
    if (b) inner = renderShapes(b.shapes, 1.8)
    else return ''
  }
  const cls = 'ico'
  return (
    '<svg class="' + cls + '" width="' + size + '" height="' + size + '" viewBox="0 0 24 24" fill="none" aria-hidden="true" focusable="false">' + inner + '</svg>'
  )
}